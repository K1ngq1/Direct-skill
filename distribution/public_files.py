"""Keep Git submissions inside the explicit public runtime file list."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
POLICY = 'distribution/public-files.json'


def public_files(ref=None):
    data = (subprocess.check_output(['git', 'show', ref + ':' + POLICY], cwd=ROOT)
            if ref else (ROOT / POLICY).read_bytes())
    files = json.loads(data)['files']
    if (not isinstance(files, list) or len(files) != len(set(files))
            or any(not isinstance(name, str) or '\\' in name or name.startswith('/')
                   or any(part in ('', '.', '..') for part in name.split('/')) for name in files)):
        raise ValueError('Invalid public runtime file list')
    return set(files)


def ignore_text(files):
    directories = {str(parent).replace('\\', '/') for name in files
                   for parent in Path(name).parents if str(parent) != '.'}
    lines = ['# Generated by python distribution/public_files.py --write-ignore',
             '# Only listed runtime source files may be committed. Local data stays on disk.', '/*']
    for directory in sorted(directories, key=lambda value: (value.count('/'), value)):
        lines.extend(['!/' + directory + '/', '/' + directory + '/*'])
    lines.extend('!/' + name for name in sorted(files))
    return '\n'.join(lines) + '\n'


def check():
    allowed = public_files()
    tracked = subprocess.check_output(['git', 'ls-files', '-z'], cwd=ROOT).decode('utf-8').split('\0')
    unexpected = sorted(name for name in tracked if name and name not in allowed)
    if unexpected:
        raise ValueError('Files outside public runtime scope:\n' + '\n'.join(unexpected))
    if (ROOT / '.gitignore').read_text(encoding='utf-8') != ignore_text(allowed):
        raise ValueError('Regenerate .gitignore with --write-ignore')
    missing = sorted(name for name in allowed if not (ROOT / name).is_file())
    if missing:
        raise ValueError('Missing runtime files:\n' + '\n'.join(missing))
    return {'status': 'passed', 'publicFiles': len(allowed)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-ignore', action='store_true')
    args = parser.parse_args()
    if args.write_ignore:
        (ROOT / '.gitignore').write_text(ignore_text(public_files()), encoding='utf-8')
    else:
        print(json.dumps(check(), ensure_ascii=False))
